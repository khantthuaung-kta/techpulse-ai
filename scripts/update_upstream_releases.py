"""Track upstream release changes without generating artificial daily commits.

Only published, non-prerelease GitHub releases are tracked. No AI or Telegram
secrets are needed. A failed source preserves its previous saved snapshot.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

REPOSITORIES = ("fastapi/fastapi", "facebook/react", "odoo/owl", "expo/expo", "microsoft/vscode")
OUTPUT = Path("data/upstream-releases.json")
REPORT = Path("docs/upstream-release-watch.md")


def newest_release(repository: str) -> dict:
    url = f"https://api.github.com/repos/{repository}/releases?per_page=15"
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "techpulse-release-watch",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if os.environ.get("GH_TOKEN"):
        headers["Authorization"] = f"Bearer {os.environ['GH_TOKEN']}"
    request = Request(url, headers=headers)
    with urlopen(request, timeout=25) as response:
        releases = json.load(response)
    for release in releases:
        if release.get("draft") or release.get("prerelease"):
            continue
        return {
            "tag": str(release["tag_name"]),
            "title": str(release.get("name") or release["tag_name"]),
            "published_at": release.get("published_at"),
            "url": str(release["html_url"]),
        }
    raise ValueError(f"No published stable release found for {repository}")


def main() -> int:
    previous = {}
    if OUTPUT.exists():
        previous = json.loads(OUTPUT.read_text(encoding="utf-8"))
    updated = dict(previous)
    successes = 0
    for repo in REPOSITORIES:
        try:
            updated[repo] = newest_release(repo)
            successes += 1
        except (HTTPError, URLError, TimeoutError, ValueError, KeyError, json.JSONDecodeError) as error:
            print(f"Warning: {repo}: {error}; keeping existing data")
    if successes == 0:
        print("No upstream sources available; refusing to replace the snapshot.")
        return 1

    updated = {key: updated[key] for key in sorted(updated)}
    if updated == previous:
        print("No actual release changes; no files updated.")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(updated, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Upstream release watch",
        "",
        "Automatically tracks actual published stable releases relevant to TechPulse AI.",
        "Sources are the upstream projects linked below. No daily filler commits are made.",
        "",
        "| Project | Latest stable tag | Published (UTC) | Release |",
        "| --- | --- | --- | --- |",
    ]
    for repo, release in updated.items():
        tag = release["tag"].replace("|", "\\|")
        published = (release.get("published_at") or "Unknown")[:10]
        lines.append(f"| `{repo}` | `{tag}` | {published} | [View release]({release['url']}) |")
    lines.extend(["", "Generated by `scripts/update_upstream_releases.py`.", ""])
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Updated upstream release watch from {successes} available sources.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
